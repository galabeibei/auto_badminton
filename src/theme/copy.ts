/**
 * Per-theme wording for the app's main user-facing text (screen titles,
 * buttons, lobby labels, dialog titles). `CLASSIC_COPY` is the original text;
 * other themes override whichever entries they want to re-word, section by
 * section, and fall back to the classic wording for the rest.
 *
 * The spoken match announcement is themed too (`announcement`): the words
 * around the player names, optionally naming the court.
 *
 * Deliberately left out: error / validation messages, import instructions,
 * table column headers and aria-labels - those need to stay plain and
 * unambiguous whatever the theme.
 */

/** Text with one bolded fragment in the middle: `[before, bold, after]`. */
export type Emphasized = readonly [string, string, string];
const em = (before: string, bold: string, after: string): Emphasized => [before, bold, after];

/** Text wrapped around a (bold) value: `[before, after]`. */
export type Wrapped = readonly [string, string];
const wrap = (before: string, after: string): Wrapped => [before, after];

/** A spoken closing phrase that names the court when it is known. */
const atCourt =
  (withCourt: (courtId: number) => string, fallback: string) =>
  (courtId?: number): string =>
    courtId ? withCourt(courtId) : fallback;

