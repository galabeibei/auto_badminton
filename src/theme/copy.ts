const mergeCopy = (overrides: CopyOverrides): Copy =>
  Object.fromEntries(
    (Object.keys(CLASSIC_COPY) as (keyof Copy)[]).map((section) => [
      section,
      { ...CLASSIC_COPY[section], ...overrides[section] },
    ]),
  ) as Copy;

// Built once so every `getCopy` call for a theme returns the same object.
const COPY_BY_THEME = Object.fromEntries(
  THEME_IDS.map((id) => [id, mergeCopy(OVERRIDES[id])]),
) as Record<ThemeId, Copy>;

export const getCopy = (id: ThemeId = DEFAULT_THEME_ID): Copy => COPY_BY_THEME[id];
